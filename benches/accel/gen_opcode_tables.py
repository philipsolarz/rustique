"""Generate crates/rustique-py/src/accel/opcodes.rs: per CPython minor, the opcodes that can
raise a synchronous exception (metadata flags HAS_ERROR / HAS_ERROR_NO_POP, minus JUMP_BACKWARD,
whose only error is the eval breaker: asynchronous, docs/ACCELERATION.md §5.8) and the number
of inline cache entries of each opcode. Fingerprint v3 canonicalizes exception tables with them
(docs/atlas/w2-floors.md §5.3). Opcode numbers and metadata are fixed within a minor; the
tables are the union over every patch release's headers given (stricter: an opcode that may
raise in any release counts).

    python benches/accel/gen_opcode_tables.py 3.14:/work/cpython/v3.14.9,/work/cpython/v3.14.10 \\
        3.15:/work/cpython/v3.15.1,/work/cpython/v3.15.2 > crates/rustique-py/src/accel/opcodes.rs
"""

from __future__ import annotations

import re
import sys


def parse(src: str) -> tuple[dict[str, int], dict[int, int], set[int]]:
    ids = {}
    for m in re.finditer(r"#define (\w+)\s+(\d+)\s*$", open(f"{src}/Include/opcode_ids.h").read(), re.M):
        ids[m.group(1)] = int(m.group(2))
    meta = open(f"{src}/Include/internal/pycore_opcode_metadata.h").read()
    flagval = {m.group(1): int(m.group(2)) for m in re.finditer(r"#define (\w+_FLAG) \((\d+)\)", meta)}
    caches_src = meta[meta.index("_PyOpcode_Caches[256] = {"):]
    caches_src = caches_src[: caches_src.index("};")]
    caches = {ids[m.group(1)]: int(m.group(2)) for m in re.finditer(r"\[(\w+)\] = (\d+),", caches_src)}
    start = re.search(r"_PyOpcode_opcode_metadata\[\d+\] = \{", meta).end()
    md = meta[start : meta.index("};", start)]
    raises = set()
    for m in re.finditer(r"\[(\w+)\] = \{ true, \w+, ([^}]*)\}", md):
        name, flags = m.group(1), m.group(2)
        v = 0
        for f in re.findall(r"\w+_FLAG", flags):
            v |= flagval[f]
        if v & (flagval["HAS_ERROR_FLAG"] | flagval["HAS_ERROR_NO_POP_FLAG"]) and name != "JUMP_BACKWARD":
            if name in ids:
                raises.add(ids[name])
    return ids, caches, raises


def main() -> None:
    out = [
        "//! Generated by benches/accel/gen_opcode_tables.py from CPython's headers (do not edit):",
        "//! per minor, the opcodes that can raise a synchronous exception and the inline cache",
        "//! entries of each opcode (fingerprint v3's canonical exception table).",
        "",
    ]
    for arg in sys.argv[1:]:
        minor, srcs = arg.split(":")
        caches_all: dict[int, int] = {}
        raises_all: set[int] = set()
        ids_ref = None
        for src in srcs.split(","):
            ids, caches, raises = parse(src)
            if ids_ref is not None and ids != ids_ref:
                sys.exit(f"{minor}: opcode numbers differ between patch releases ({src})")
            ids_ref = ids
            for k, v in caches.items():
                if caches_all.setdefault(k, v) != v:
                    sys.exit(f"{minor}: cache sizes differ for opcode {k} ({src})")
            raises_all |= raises
        tag = minor.replace(".", "_")
        words = [0, 0, 0, 0]
        for op in raises_all:
            words[op // 64] |= 1 << (op % 64)
        out.append(f"/// CPython {minor}: opcodes that can raise (bit per opcode).")
        out.append(f"pub const RAISES_{tag}: [u64; 4] = [{', '.join(f'0x{w:016x}' for w in words)}];")
        cache_list = ", ".join(str(caches_all.get(i, 0)) for i in range(256))
        out.append(f"/// CPython {minor}: inline cache entries per opcode.")
        out.append(f"pub const CACHES_{tag}: [u8; 256] = [{cache_list}];")
        out.append(f"/// CPython {minor}: `EXTENDED_ARG`.")
        out.append(f"pub const EXTENDED_ARG_{tag}: u8 = {ids_ref['EXTENDED_ARG']};")
        out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
