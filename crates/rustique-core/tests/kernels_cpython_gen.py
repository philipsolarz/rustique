"""Generate the expected values in `kernels_cpython.rs` by running CPython itself.

Inputs are rebuilt from the same xorshift64* stream on both sides (see `Rng` in the Rust
file), so only CPython's results are embedded. Run with the project's Python (3.12+):

    python crates/rustique-core/tests/kernels_cpython_gen.py > /tmp/expected.rs

and replace everything after the `// BEGIN GENERATED` line of `kernels_cpython.rs` with it.
"""

import math
import struct
import sys

MASK = (1 << 64) - 1


class Rng:
    def __init__(self, seed):
        self.state = seed

    def next(self):
        s = self.state
        s ^= s >> 12
        s ^= (s << 25) & MASK
        s ^= s >> 27
        self.state = s
        return (s * 0x2545F4914F6CDD1D) & MASK

    def unit(self):
        return (self.next() >> 11) * 2.0**-53

    def pick(self, items):
        return items[self.next() % len(items)]


INF = math.inf
NAN = math.nan
SPECIALS = [INF, -INF, NAN, 0.0, -0.0, 1e308, -1e308, 5e-324, -5e-324,
            2.0**53, 2.0**53 + 2, 1e16, -1e16, 1.0, -1.0]
BIGS = [1e16, 1e20, 2.0**60, 1e100]
ZEROS = [0.0, -0.0, 1.0, -1.0, NAN]
ZEROS_NO_NAN = [0.0, -0.0, 1.0, -1.0]
ZEROS_MIN = [0.0, -0.0, 1.0, NAN]
ZEROS_MAX = [0.0, -0.0, -1.0, NAN]
NEGZERO = [-0.0, -0.0, -0.0, -5e-324, 5e-324]
HUGE = [1e308, -1e308, 1.7e308, 8.98846567431158e307]


def wide(r):
    negative = r.next() & 1
    m = r.unit()
    e = r.next() % 121 - 60
    x = math.ldexp(m, e)
    return -x if negative else x


def draw(kind, r):
    if kind == "uniform":
        return r.unit() * 2.0 - 1.0
    if kind == "wide":
        return wide(r)
    if kind == "special":
        return r.pick(SPECIALS) if r.next() % 8 == 0 else wide(r)
    if kind == "cancel":
        if r.next() % 2 == 0:
            big = r.pick(BIGS)
            return big if r.next() & 1 else -big
        return r.unit()
    if kind == "intfloat":
        return float(2**53 + r.next() % 16 - 8)
    if kind == "plusinf":
        return INF if r.next() % 50 == 0 else wide(r)
    if kind == "negzero":
        return r.pick(NEGZERO)
    if kind == "huge":
        return r.pick(HUGE) if r.next() % 4 == 0 else wide(r)
    if kind == "zeros":
        return r.pick(ZEROS)
    if kind == "zeros_min":
        return r.pick(ZEROS_MIN)
    if kind == "zeros_max":
        return r.pick(ZEROS_MAX)
    if kind == "zeros_no_nan":
        return r.pick(ZEROS_NO_NAN)
    raise ValueError(kind)


def floats(kind, n, seed):
    r = Rng(seed)
    return [draw(kind, r) for _ in range(n)]


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def digest(values):
    """Order-sensitive hash of the bit patterns (the shift spreads sign bits downward)."""
    h = 0xCBF29CE484222325
    for v in values:
        h = ((h ^ bits(v)) * 0x100000001B3) & MASK
        h ^= h >> 32
    return h


def nan_or_bits(x):
    return "NAN" if math.isnan(x) else f"0x{bits(x):016x}"


SUM_KINDS = ["uniform", "wide", "special", "cancel", "intfloat", "plusinf", "negzero", "huge"]
SUM_LENS = [1, 2, 3, 10, 100, 1000, 100_000]
EXTREME_KINDS = ["zeros", "zeros_min", "zeros_max", "special", "wide"]
EXTREME_LENS = [1, 2, 5, 50, 1000, 300_000]
SORT_KINDS = ["zeros_no_nan", "wide", "intfloat", "uniform"]
SORT_LENS = [2, 7, 100, 5000, 100_000]

I64_POOL = [0, 1, -1, 2**53, 2**53 + 1, 2**53 - 1, 2**63 - 1, -2**63, -2**63 + 1, 2**62,
            -(2**53) - 1, 12345]
U64_POOL = [0, 1, 2**53 + 1, 2**63, 2**63 + 1, 2**64 - 1, 2**64 - 2048, 2**64 - 1024, 2**53]
FLOAT_POOL = [2.0**53, 2.0**63, 2.0**64, -(2.0**63), 0.5, -0.0, INF, NAN]


def lex_case(seed):
    r = Rng(seed)
    pool = I64_POOL if r.next() & 1 else U64_POOL
    n = 1 + r.next() % 5
    ints = [r.pick(pool) for _ in range(n)]
    fl = []
    for i in ints:
        c = r.next() % 6
        fl.append(r.pick(FLOAT_POOL) if c == 0 else float(r.pick(pool)) if c == 1 else float(i))
    m = r.next() % 3
    if m == 1:
        fl = fl[: r.next() % (n + 1)]
    elif m == 2:
        fl.append(float(r.pick(pool)))
    return ints, fl


def mask(a, b):
    return sum(bit << k for k, bit in enumerate([a == b, a < b, a <= b, a > b, a >= b]))


def main():
    out = sys.stdout.write
    out(f"// Generated by kernels_cpython_gen.py with CPython {sys.version.split()[0]}.\n")
    out("const SUM_CASES: &[(&str, usize, u64, &str, &str)] = &[\n")
    seed = 1
    for kind in SUM_KINDS:
        for n in SUM_LENS:
            xs = floats(kind, n, seed)
            s64 = nan_or_bits(sum(xs))
            s32 = nan_or_bits(sum(f32(x) for x in xs)) if kind in ("uniform", "wide", "intfloat") else "-"
            out(f'    ("{kind}", {n}, {seed}, "{s64}", "{s32}"),\n')
            seed += 1
    out("];\n\n")
    out("const EXTREME_CASES: &[(&str, usize, u64, &str, &str)] = &[\n")
    for kind in EXTREME_KINDS:
        for n in EXTREME_LENS:
            xs = floats(kind, n, seed)
            out(f'    ("{kind}", {n}, {seed}, "{nan_or_bits(min(xs))}", "{nan_or_bits(max(xs))}"),\n')
            seed += 1
    out("];\n\n")
    out("const SORT_CASES: &[(&str, usize, u64, u64, u64)] = &[\n")
    for kind in SORT_KINDS:
        for n in SORT_LENS:
            xs = floats(kind, n, seed)
            out(f'    ("{kind}", {n}, {seed}, 0x{digest(sorted(xs)):016x}, 0x{digest(sorted(xs, reverse=True)):016x}),\n')
            seed += 1
    out("];\n\n")
    out("/// `(seed, mask of a <op> b, mask of b <op> a)`; bits: ==, <, <=, >, >=.\n")
    out("const LEX_CASES: &[(u64, u8, u8)] = &[\n")
    for _ in range(300):
        a, b = lex_case(seed)
        out(f"    ({seed}, {mask(a, b)}, {mask(b, a)}),\n")
        seed += 1
    out("];\n")


main()
