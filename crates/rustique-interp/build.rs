//! Compiles the checked-in handler sets (gen/v<release>/, see tools/gen.py) for the build
//! interpreter's minor version and configuration (GIL or free-threaded), with clang >= 19
//! (preserve_none + musttail: CPython's tail-calling ABI). No CPython source is needed: each
//! set carries the headers it reads and the pyconfig.h of the verified builds.
//!
//! Only x86_64 Linux (glibc) is supported; anywhere else, or without a suitable clang, the
//! crate builds no sets and the tier refuses with "built without handlers".
//! `RUSTIQUE_INTERP_REQUIRE=1` (CI) turns a missing compiler or PGO tool into a build error.
//! `RUSTIQUE_INTERP_CC` names the compiler. `RUSTIQUE_INTERP_PGO=gen` builds instrumented
//! sets for training (tools/pgo.sh); otherwise gen/pgo-<cfg>.proftext is used when present.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    println!("cargo::rustc-check-cfg=cfg(rq_interp_sets)");
    println!("cargo:rerun-if-changed=c");
    println!("cargo:rerun-if-changed=gen");
    for v in ["RUSTIQUE_INTERP_CC", "RUSTIQUE_INTERP_REQUIRE", "RUSTIQUE_INTERP_PGO"] {
        println!("cargo:rerun-if-env-changed={v}");
    }
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let require = env::var("RUSTIQUE_INTERP_REQUIRE").is_ok_and(|v| v == "1");
    let mut sets_rs = String::from("// Generated by build.rs: the handler sets compiled into this build.\n");
    let mut entries = Vec::new();

    let supported = env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("x86_64")
        && env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux")
        && env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("gnu");
    let cfg = pyo3_build_config::get();
    let v = cfg.version();
    let minor = (v.major, v.minor);
    let ft = cfg.is_free_threaded();
    let tag = if ft { "t" } else { "gil" };

    let clang = if supported { find_clang() } else { None };
    if supported && clang.is_none() {
        if require {
            panic!("RUSTIQUE_INTERP_REQUIRE=1 but no clang >= 19 found (set RUSTIQUE_INTERP_CC)");
        }
        println!("cargo:warning=rustique-interp: no clang >= 19: building without handler sets");
    }
    if let Some((cc, suffix)) = clang.filter(|_| supported) {
        let gen_dir = Path::new("gen");
        let mut releases: Vec<(u32, u32, u32, String)> = fs::read_dir(gen_dir)
            .map(|d| {
                d.filter_map(|e| e.ok())
                    .filter_map(|e| {
                        let n = e.file_name().into_string().ok()?;
                        let mut p = n.strip_prefix('v')?.split('_').map(|x| x.parse::<u32>().ok());
                        Some((p.next()??, p.next()??, p.next()??, n))
                    })
                    .collect()
            })
            .unwrap_or_default();
        releases.sort();
        let pgo_gen = env::var("RUSTIQUE_INTERP_PGO").as_deref() == Ok("gen");
        for (maj, min, patch, dir) in &releases {
            if (u32::from(minor.0), u32::from(minor.1)) != (*maj, *min) {
                continue;
            }
            let rel = gen_dir.join(dir);
            if !rel.join(format!("config-{tag}")).join("pyconfig.h").exists() {
                continue;
            }
            let set = format!("{dir}_{tag}");
            let release_tag = format!("{maj}.{min}.{patch}");
            let mut b = cc::Build::new();
            b.compiler(&cc)
                .file("c/rq_handlers.c")
                .out_dir(out.join(&set))
                .cargo_metadata(true)
                .opt_level(3)
                .debug(false)
                .warnings(false)
                .pic(true)
                .flag("-std=gnu11")
                .flag("-fvisibility=hidden")
                .flag("-fno-semantic-interposition")
                .flag("-fno-strict-overflow")
                .flag("-fno-omit-frame-pointer")
                .flag("-mno-omit-leaf-frame-pointer")
                .flag("-w")
                .define("NDEBUG", None)
                .define("Py_BUILD_CORE_MODULE", None)
                .define("RQ_SET", set.as_str())
                .define("RQ_RELEASE_TAG", format!("\"{release_tag}\"").as_str());
            let defs = fs::read_to_string(rel.join(format!("defs-{tag}.txt"))).unwrap_or_default();
            for d in defs.split_whitespace() {
                let d = d.trim_start_matches("-D");
                match d.split_once('=') {
                    Some((k, v)) => b.define(k, v),
                    None => b.define(d, None),
                };
            }
            // Headers: one tree per set (the base release's, named in base.txt, with this
            // release's files laid over it), so quoted includes resolve next to the file.
            let hdr = out.join(format!("{set}-headers"));
            let _ = fs::remove_dir_all(&hdr);
            if let Ok(base) = fs::read_to_string(rel.join("base.txt")) {
                copy_tree(&gen_dir.join(base.trim()), &hdr);
            }
            copy_tree(&rel, &hdr);
            b.include(rel.join(format!("config-{tag}"))).include(&rel).include("c");
            b.include(hdr.join("python"));
            for sub in ["", "internal", "internal/mimalloc"] {
                b.include(hdr.join("include").join(sub));
            }
            if pgo_gen {
                b.flag("-fprofile-instr-generate").define("RQ_PGO_GEN", None);
            } else {
                // One profile per configuration serves every release: functions are matched
                // by name and CFG hash, so code a later release changed just gets none.
                let prof = gen_dir.join(format!("pgo-{tag}.proftext"));
                if prof.exists() {
                    match merge_profile(&suffix, &prof, &out.join(format!("{set}.profdata"))) {
                        Some(p) => {
                            b.flag(format!("-fprofile-instr-use={}", p.display()));
                            b.flag("-Wno-profile-instr-out-of-date");
                            b.flag("-Wno-profile-instr-unprofiled");
                        }
                        None if require => {
                            panic!("RUSTIQUE_INTERP_REQUIRE=1 but llvm-profdata{suffix} is missing (PGO)")
                        }
                        None => println!(
                            "cargo:warning=rustique-interp: llvm-profdata{suffix} not found: {set} built without PGO"
                        ),
                    }
                }
            }
            b.compile(&format!("rqinterp_{set}"));
            entries.push((set, release_tag));
        }
        if pgo_gen && !entries.is_empty() {
            link_profile_runtime(&cc);
        }
    }

    for (set, _) in &entries {
        writeln!(sets_rs, "unsafe extern \"C\" {{ fn rq_api_{set}() -> *const crate::RqApi; }}").unwrap();
    }
    writeln!(sets_rs, "/// (CPython release, free-threaded, the set's interface).").unwrap();
    writeln!(sets_rs, "pub(crate) static SETS: &[(&str, bool, unsafe extern \"C\" fn() -> *const crate::RqApi)] = &[").unwrap();
    for (set, release) in &entries {
        writeln!(sets_rs, "    (\"{release}\", {ft}, rq_api_{set}),").unwrap();
    }
    writeln!(sets_rs, "];").unwrap();
    fs::write(out.join("sets.rs"), sets_rs).unwrap();
    if !entries.is_empty() {
        println!("cargo:rustc-cfg=rq_interp_sets");
    }
}

/// The first of `$RUSTIQUE_INTERP_CC`, clang-22 .. clang-19, clang whose major version is at
/// least 19, with its version suffix ("-20" or "").
fn find_clang() -> Option<(String, String)> {
    let mut cands: Vec<(String, String)> = Vec::new();
    if let Ok(cc) = env::var("RUSTIQUE_INTERP_CC") {
        let suffix = cc.rsplit_once("clang").map(|(_, s)| s.to_owned()).unwrap_or_default();
        cands.push((cc, suffix));
    }
    for v in (19..=22).rev() {
        cands.push((format!("clang-{v}"), format!("-{v}")));
    }
    cands.push(("clang".into(), String::new()));
    for (cc, suffix) in cands {
        let Ok(o) = Command::new(&cc).arg("--version").output() else { continue };
        let s = String::from_utf8_lossy(&o.stdout);
        let major = s
            .split("version ")
            .nth(1)
            .and_then(|r| r.split('.').next())
            .and_then(|m| m.trim().parse::<u32>().ok());
        if major.is_some_and(|m| m >= 19) {
            return Some((cc, suffix));
        }
    }
    None
}

/// Copy `src/{python,include}` into `dst/` (overwriting).
fn copy_tree(src: &Path, dst: &Path) {
    fn walk(from: &Path, to: &Path) {
        fs::create_dir_all(to).unwrap();
        for e in fs::read_dir(from).unwrap().flatten() {
            let p = e.path();
            let t = to.join(e.file_name());
            if p.is_dir() {
                walk(&p, &t);
            } else {
                fs::copy(&p, &t).unwrap();
            }
        }
    }
    for top in ["python", "include"] {
        if src.join(top).is_dir() {
            walk(&src.join(top), &dst.join(top));
        }
    }
}

fn merge_profile(suffix: &str, text: &Path, dst: &Path) -> Option<PathBuf> {
    let tool = format!("llvm-profdata{suffix}");
    let ok = Command::new(&tool)
        .args(["merge", "-o"])
        .arg(dst)
        .arg(text)
        .status()
        .is_ok_and(|s| s.success());
    ok.then(|| dst.to_path_buf())
}

fn link_profile_runtime(cc: &str) {
    let o = Command::new(cc).arg("--print-file-name=libclang_rt.profile-x86_64.a").output();
    let mut path = o.map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned()).unwrap_or_default();
    if !Path::new(&path).is_absolute() {
        let o = Command::new(cc).arg("--print-runtime-dir").output();
        let dir = o.map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned()).unwrap_or_default();
        path = format!("{dir}/libclang_rt.profile.a");
        if !Path::new(&path).exists() {
            path = format!("{dir}/libclang_rt.profile-x86_64.a");
        }
    }
    let p = Path::new(&path);
    let dir = p.parent().expect("profile runtime directory");
    let name = p.file_stem().unwrap().to_string_lossy();
    println!("cargo:rustc-link-search=native={}", dir.display());
    println!("cargo:rustc-link-lib=static={}", name.trim_start_matches("lib"));
}
